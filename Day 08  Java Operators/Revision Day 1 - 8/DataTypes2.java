class DataTypes2
{	
	static byte age = 20;
	static short salary = 2021;
	static int accountBalance = 1123000;
	static long accountBalance2 = 11230001;
	static float percentage = 96.8f;
	static double pie = 3.143d;
	static boolean isEligible = true;
	static char grade = 'A';
	
	public static void main(String args[])
	{
		System.out.println("Age : " +age);
		System.out.println("Salary : " +salary);
		System.out.println("Account Balance : " +accountBalance );
		System.out.println("Percentage : " +percentage);
		System.out.println("Grade : " +grade);
		System.out.println("Eligible : " +isEligible);
		System.out.println("Double : " +pie);
		System.out.println("Long : " +accountBalance2);
	}
}
		